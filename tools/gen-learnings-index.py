def sections(text):
    lines = text.splitlines()
    out = []
    for i, line in enumerate(lines, 1):
        m = re.match(r"^## (.+?)\s*$", line)
        if not m:
            continue
        h = m.group(1)
        tm = re.search(r"\(([^()]*\d{4}(?:-\d{2}-\d{2})?)\)\s*$", h)
        lesson = h[: tm.start()].rstrip() if tm else h
        out.append({"line": i, "heading": h, "lesson": lesson})
    # Attach each section's body — the model cross-reference keys off the body,
    # because a section is usually *about* a model that its heading never names.
    for k, s in enumerate(out):
        end = out[k + 1]["line"] - 1 if k + 1 < len(out) else len(lines)
        s["body"] = "\n".join(lines[s["line"] : end])
    return out


# A section counts for a family if its heading names it, or its body mentions it
# this many times — enough to mean "substantially about", not a passing mention.
BODY_MENTIONS = 3


def in_family(sec, pat):
    if re.search(pat, sec["heading"]):
        return True
    return len(re.findall(pat, sec["body"])) >= BODY_MENTIONS


def topic_of(sec):
    for prefix, t in OVERRIDES.items():
        if sec["heading"].startswith(prefix):
            return t
    for name, pat in TOPICS:
        if re.search(pat, sec["heading"]):
            return name
    # Not a transferable lesson but it names a backend → it is a port note.
    if any(re.search(pat, sec["heading"]) for _, pat in MODELS):
        return PORTS
    return "Uncategorised"


def build_index(secs):
    for s in secs:
        s["topic"] = topic_of(s)

    order = [n for n, _ in TOPICS] + [PORTS, "Uncategorised"]
    lines = ["# LEARNINGS.md — index",
             "",
             "GENERATED by `tools/gen-learnings-index.py`. Do not hand-edit; re-run it.",
             "",
             "`LEARNINGS.md` is ~800 KB and nobody reads it whole. Scan this index, then jump:",
             "",
             "```bash",
             'grep -n "<heading text>" LEARNINGS.md   # then Read with that offset',
             "```",
             "",
             "Every heading states its lesson in full, so **the index is the summary** — if a",
             "line does not sound relevant, neither is the section under it. `L<n>` is the line",
             "in LEARNINGS.md at generation time; re-run the tool if the numbers look off.",
             "",
             "Roughly half the file is transferable method (the topic groups) and half is",
             "per-backend porting detail (Per-model port notes + the family cross-reference).",
             "Reach for the topic groups when you are stuck on a *technique*, and the",
             "cross-reference when you already know which model you are touching.",
             ""]

    lines += [f"## Index by topic ({len(secs)} lessons)", ""]
    for t in order:
        group = [s for s in secs if s["topic"] == t]
        if not group:
            continue
        lines.append(f"**{t}** ({len(group)})")
        lines.append("")
        for s in group:
            lines.append(f"- L{s['line']} — {s['lesson']}")
        lines.append("")

    lines += ["## Cross-reference by model / family", "",
              "A section is listed when its heading names the family, or its body mentions it",
              f"at least {BODY_MENTIONS} times. Sections appear under several families; this is a",
              "lookup, not a partition.",
              ""]
    for name, pat in MODELS:
        hits = [s for s in secs if in_family(s, pat)]
        if not hits:
            continue
        lines.append(f"- **{name}** ({len(hits)}) — " + ", ".join(f"L{s['line']}" for s in hits))
    lines.append("")
    return "\n".join(lines)


def main():
    text = LEARNINGS.read_text()

    # 1. Put the pointer in place FIRST, then read line numbers off the result —
    #    otherwise the insertion shifts every number the index is about to cite.
    n = len(sections(text))
    pointer = POINTER.format(n=n)
    if BEGIN in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        new_learnings = pre + pointer + post
    else:
        marker = "\n---\n"
        i = text.index(marker) + len(marker)
        new_learnings = text[:i] + "\n" + pointer + "\n" + text[i:]

    # 2. Sections, with their final line numbers.
    secs = sections(new_learnings)
    if not secs:
        sys.exit("no '## ' sections found — wrong file?")
    index = build_index(secs)

    if "--check" in sys.argv:
        stale = []
        if new_learnings != text:
            stale.append("LEARNINGS.md pointer")
        if not INDEX.exists() or INDEX.read_text() != index:
            stale.append(str(INDEX))
        if stale:
            sys.exit(f"out of date: {', '.join(stale)} — run: python tools/gen-learnings-index.py")
        print(f"LEARNINGS index up to date ({len(secs)} sections)")
        return

    if new_learnings != text:
        LEARNINGS.write_text(new_learnings)
    INDEX.parent.mkdir(parents=True, exist_ok=True)
    INDEX.write_text(index)

    uncat = [s for s in secs if s["topic"] == "Uncategorised"]
    print(f"indexed {len(secs)} sections -> {INDEX} ({len(index)} bytes)")
    for t in [n for n, _ in TOPICS] + [PORTS]:
        c = sum(1 for s in secs if s["topic"] == t)
        if c:
            print(f"   {c:3}  {t}")
    if uncat:
        print(f"{len(uncat)} UNCATEGORISED — add a rule or an OVERRIDES entry:")
        for s in uncat:
            print(f"   L{s['line']} {s['lesson'][:88]}")


if __name__ == "__main__":
    main()
