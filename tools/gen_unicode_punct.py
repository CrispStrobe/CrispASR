"""Generate src/core/unicode_punct.h: the Unicode P* (punctuation) ranges.

core/unicode_categ.h folds P* and S* into one CAT_P class, which is right for
the BPE pre-tokenizers. NeMo's decoders need P* alone: its
extract_punctuation_from_vocab() keeps characters whose
unicodedata.category() starts with 'P', so '+', '$' or '|' are not included.

    python tools/gen_unicode_punct.py > src/core/unicode_punct.h
    tools/format.sh --fix src/core/unicode_punct.h
"""
import unicodedata

ranges, start = [], None
for cp in range(0x110000):
    p = unicodedata.category(chr(cp)).startswith("P")
    if p and start is None:
        start = cp
    elif not p and start is not None:
        ranges.append((start, cp - 1))
        start = None

