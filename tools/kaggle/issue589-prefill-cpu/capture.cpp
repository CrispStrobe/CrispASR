// Direct pinned base backend driver, not the CLI adapter. No model downloader.
#include "vibevoice.cpp"

int main(int argc, char** argv) {
    if (argc != 3)
        return 2;
    setenv("CRISPASR_VIBEVOICE_TTS_CAPTURE_FIRST_FRAME", argv[2], 1);
    setenv("CRISPASR_VIBEVOICE_TTS_CAPTURE_PREFILL_BLOCKS", "1", 1);
    setenv("CRISPASR_VIBEVOICE_TTS_CAPTURE_PREFILL_ONLY", "1", 1);
    setenv("CRISPASR_VIBEVOICE_TTS_SEMANTIC_FEEDBACK", "1", 1);
    setenv("CRISPASR_VIBEVOICE_TTS_REFRESH_NEGATIVE", "1", 1);
    setenv("CRISPASR_VIBEVOICE_SEMANTIC_F16", "1", 1);
    setenv("CRISPASR_VIBEVOICE_TTS_TOKEN_CONSTRAINT", "0", 1);
    setenv("CRISPASR_VIBEVOICE_TTS_FLASH_ATTN", "1", 1);
    auto params = vibevoice_context_default_params();
    params.use_gpu = false;
    params.n_threads = 1;
    params.seed = 42;
    params.tts_steps = 20;
    params.cfg_scale = 1.3f;
    auto* ctx = vibevoice_init_from_file(argv[1], params);
    if (!ctx)
        return 3;
    int samples = 0;
    float* audio = vibevoice_synthesize(ctx, "This audio was generated by artificial intelligence.", &samples);
    if (audio || samples != 0) {
        free(audio);
        vibevoice_free(ctx);
        return 4;
    }
    char path[4096];
    snprintf(path, sizeof(path), "%s/prefill_capture_complete.bin", argv[2]);
    FILE* marker = fopen(path, "rb");
    if (!marker) {
        vibevoice_free(ctx);
        return 5;
    }
    fseek(marker, 0, SEEK_END);
    bool complete = ftell(marker) == 16;
    fclose(marker);
    vibevoice_free(ctx);
    fprintf(stderr, "direct base backend: prefill-only diagnostic; no diffusion/audio; complete=%d\n", complete);
    return complete ? 0 : 6;
}
